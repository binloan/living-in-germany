// Writes app.yaml (gitignored) from .env so no project settings live in the repo.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import 'dotenv/config';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const env = process.env;
const q = (v) => JSON.stringify(String(v));

// Forwarded to the running service; everything else in .env is deploy-time only.
const forward = ['CONTACT_EMAIL', 'BASEMAP_STYLE_URL', 'TRANSITOUS_URL', 'ROUTE_SOURCE', 'ROUTE_COOLDOWN_MIN', 'VBB_API_URL', 'VBB_ACCESS_ID', 'PHOTON_URL', 'NOMINATIM_URL', 'RATE_LIMIT_PER_MIN', 'PRICE_STORE', 'PRICE_DATABASE', 'PRICE_COLLECTION', 'PRICE_WRITES_PER_MIN'];
const vars = forward.filter((k) => env[k]).map((k) => `  ${k}: ${q(env[k])}`).join('\n');

const yaml = `# Generated by scripts/gen-app-yaml.mjs from .env. Do not commit.
runtime: ${env.GAE_RUNTIME || 'nodejs22'}
service: ${env.GAE_SERVICE || 'default'}
instance_class: ${env.GAE_INSTANCE_CLASS || 'F1'}
automatic_scaling:
  max_instances: ${Number(env.GAE_MAX_INSTANCES) || 2}
${vars ? `env_variables:\n${vars}\n` : ''}handlers:
  - url: /.*
    secure: always
    script: auto
`;
fs.writeFileSync(path.join(root, 'app.yaml'), yaml);
console.log('app.yaml written');
